#!/usr/bin/env bash
# The only way an agent pushes a branch and opens or updates its pull request
# in this repository. Adapted from the Agent-kit pr-pipeline Pattern guide
# (v1.0.0-beta.9); see docs/agents/pr-pipeline.md.
#
# Before anything is pushed it checks the drafter's merge base against its
# own, the body's AI notice, Merge risk line and header lines, each label
# against docs/agents/pr-labels.txt, and the branch's paths for secret-looking
# files. It never force-pushes, assigns the pull request to the gh user and
# requests only the reviewers it is given. Each failure ends with a trailer
# that names a reason and the next command to run.
#
#   bash scripts/development/pr-runner.sh --title <text> --body-file <path> --merge-base <sha>
#        [--base <branch>] [--label <name>]... [--reviewer <login>]... [--draft]
#
# There is deliberately no force-push flag. Do not add one.
# On Windows, run it from Git Bash.

set -uo pipefail

RUNNER="bash scripts/development/pr-runner.sh"
DEFAULT_BASE="main"
# One label per line; lines starting with # are comments.
LABEL_ALLOWLIST="docs/agents/pr-labels.txt"
# The first line of every agent-drafted body in this repository.
AI_NOTICE='> *This was generated by AI.*'
# The Merge risk lines the drafter writes. Keep them equal to the drafter's rule.
RISK_LINE='^\*\*Reversible:\*\* (yes|no)( — .+)?$'
# RADIUS_WORDS is the only list of blast radius words; docs and drafters point here.
RADIUS_WORDS='none|docs|ci|tooling|backend|frontend|api|auth|stored-data'
RADIUS_LINE="^\\*\\*Blast radius:\\*\\* (${RADIUS_WORDS})( — .+)?\$"
# A closing keyword inside a code span links the issue but never closes it.
# CODE_SPAN pulls out each `...` span on a line, pairing backticks from the
# left, and CLOSING_KEYWORD is then searched inside the spans only. Prose
# between two spans (Rename `foo` to `bar`; resolves #12) is not a span.
# shellcheck disable=SC2016 # the backticks are literal, not a command.
CODE_SPAN='`[^`]*`'
CLOSING_KEYWORD='\b(close[sd]?|fix(e[sd])?|resolve[sd]?) #[0-9]+'

trailer() {
  # trailer <reason> <hint> [scope] [paths]
  {
    printf -- '---\n'
    printf 'pr-runner: failed\n'
    printf 'reason: %s\n' "$1"
    [ -n "${3:-}" ] && printf 'scope: %s\n' "$3"
    [ -n "${4:-}" ] && printf 'paths: %s\n' "$4"
    printf 'hint: %s\n' "$2"
    printf -- '---\n'
  } >&2
}

# Failure reasons. This list is the only copy; docs/agents/pr-pipeline.md and
# the create-pull-request skill point here. Agents parse these names: add a
# reason, never rename one. Each fail call's hint says what to do next.
#   usage       a missing or unknown argument
#   auth        gh is not logged in, or cannot read the repository or user
#   on-base     detached HEAD, or on the base branch
#   merge-base  missing, abbreviated or different merge base, or the base
#               cannot be resolved
#   no-commits  nothing between the base and HEAD
#   body        a header line left in the body, no AI notice, or a closing
#               keyword inside a code span
#   risk        unreadable **Reversible:** or **Blast radius:** line
#   label       a label off the allowlist, or the API refused one (scope)
#   secret      the branch adds a secret-looking path (paths lists them)
#   diverged    the remote branch has commits this one lacks, or a force
#               flag was passed
#   push        git push failed
#   create      gh pr create, the update or the reviewer request failed
fail() {
  # fail <message> <reason> <hint> [scope] [paths]
  printf 'pr-runner: %s\n' "$1" >&2
  trailer "$2" "$3" "${4:-}" "${5:-}"
  exit 1
}

# Same file-name rule as commit-runner.sh: a backstop, not a secret scanner.
is_secret_path() {
  local base="${1##*/}"
  case "$base" in
    .env.example | .env.sample | .env.template) return 1 ;;
    .env | .env.*) return 0 ;;
    credentials.json) return 0 ;;
    *.pem | *.p12 | *.pfx | *.keystore | *.key) return 0 ;;
    id_rsa | id_dsa | id_ecdsa | id_ed25519) return 0 ;;
  esac
  return 1
}

USAGE="$RUNNER --title <text> --body-file <path> --merge-base <sha> [--base <branch>] [--label <name>]... [--reviewer <login>]... [--draft]"

title=""
body_file=""
merge_base=""
base=""
draft=false
labels=()
reviewers=()

need_value() {
  [ "$2" -ge 2 ] || fail "$1 needs a value." usage "$USAGE"
}

while [ "$#" -gt 0 ]; do
  case "$1" in
    --title) need_value "$1" "$#"; title="$2"; shift 2 ;;
    --body-file) need_value "$1" "$#"; body_file="$2"; shift 2 ;;
    --merge-base) need_value "$1" "$#"; merge_base="$2"; shift 2 ;;
    --base) need_value "$1" "$#"; base="$2"; shift 2 ;;
    --label) need_value "$1" "$#"; labels+=("$2"); shift 2 ;;
    --reviewer) need_value "$1" "$#"; reviewers+=("$2"); shift 2 ;;
    --draft) draft=true; shift ;;
    --force | --force-with-lease)
      fail "$1 is not supported: agents never force-push here." diverged \
        "Merge origin/<base> into the branch instead of rebasing, then run $RUNNER again."
      ;;
    -h | --help) sed -n '2,18p' "$0"; exit 0 ;;
    *) fail "unknown argument: $1" usage "$USAGE" ;;
  esac
done

[ -n "$title" ] || fail "--title is required." usage "$USAGE"
[ -n "$body_file" ] && [ -r "$body_file" ] || fail "--body-file is required and must be readable." usage "$USAGE"
[ -n "$merge_base" ] || fail "--merge-base is required: pass the MERGE-BASE: SHA from the draft. A draft without one was not read from the branch." \
  merge-base "Call the pr-drafter again; never compute the SHA yourself."

gh auth status >/dev/null 2>&1 || fail "gh is not authenticated." auth "gh auth login, then run $RUNNER again."

branch="$(git branch --show-current)"
[ -n "$branch" ] || fail "not on a branch." on-base "Check out the feature branch, then run $RUNNER again."
base="${base:-$DEFAULT_BASE}"
[ "$branch" != "$base" ] || fail "refusing to open a pull request from the base branch '$base'." on-base \
  "Create a branch per docs/agents/branch-names.md, then run $RUNNER again."

# 1. Proof of inspection: the drafter's merge base must match this branch's.
computed="$(git merge-base "origin/$base" HEAD 2>/dev/null || true)"
[ -n "$computed" ] || fail "cannot compute the merge base with 'origin/$base'." merge-base \
  "git fetch origin $base (with history), call the pr-drafter again, then run $RUNNER again."
supplied="$(printf '%s' "$merge_base" | tr '[:upper:]' '[:lower:]')"
[[ "$supplied" =~ ^[0-9a-f]{40}$ ]] || fail "--merge-base '$merge_base' is not the full 40-character SHA git merge-base prints." \
  merge-base "Call the pr-drafter again; never compute the SHA yourself."
[ "$computed" = "$supplied" ] || fail "--merge-base $supplied does not match this branch's merge base $computed. The draft describes another branch or base, or was written without inspecting it." \
  merge-base "Call the pr-drafter again (with the same --base you pass here)."

[ -n "$(git rev-list "$computed..HEAD")" ] || fail "no commits between 'origin/$base' and '$branch'." no-commits \
  "Commit through the commit-change skill first."

# 2. The body: no header lines, the AI notice, a readable Merge risk block,
#    and no closing keyword inside a code span.
if grep -Eq '^(TITLE|LABELS|MERGE-BASE):' "$body_file"; then
  fail "the body file still holds a TITLE:, LABELS: or MERGE-BASE: line." body \
    "Write only the part from the first ## heading (after the AI notice) to the body file."
fi
first_line="$(grep -m1 '[^[:space:]]' "$body_file" || true)"
[ "$first_line" = "$AI_NOTICE" ] || fail "the body does not start with the line: $AI_NOTICE" body \
  "Send the draft back to the pr-drafter with this message."
grep -Eq "$RISK_LINE" "$body_file" || fail "the body has no readable '**Reversible:** yes|no' line." risk \
  "Send the draft back to the pr-drafter with this message. Do not fix the line yourself."
grep -Eq "$RADIUS_LINE" "$body_file" || fail "the body has no readable '**Blast radius:** <word>' line (words: ${RADIUS_WORDS//|/, })." risk \
  "Send the draft back to the pr-drafter with this message. Do not fix the line yourself."
# grep -c reads every span, so pipefail never sees a SIGPIPE from an early exit.
if [ "$(grep -oE "$CODE_SPAN" "$body_file" | grep -Eic "$CLOSING_KEYWORD")" -gt 0 ]; then
  fail "a closing keyword is inside backticks, so it would link the issue but never close it." body \
    "Send the draft back to the pr-drafter with this message."
fi

# 3. Labels: only names on the allowlist. None is valid.
if [ "${#labels[@]}" -gt 0 ]; then
  [ -r "$LABEL_ALLOWLIST" ] || fail "cannot read the label allowlist $LABEL_ALLOWLIST." label "Run $RUNNER from the repository root."
  for label in "${labels[@]}"; do
    grep -v '^#' "$LABEL_ALLOWLIST" | grep -Fxq -- "$label" ||
      fail "'$label' is not on the label allowlist $LABEL_ALLOWLIST." label \
        "Drop the label, or send the draft back to the pr-drafter. Workflow labels (agent:*, team:*, ready-for-*) are never set here." "$label"
  done
fi

# 4. Secret-looking paths anywhere in the branch's diff.
blocked=""
while IFS= read -r -d '' path; do
  [ -n "$path" ] || continue
  if is_secret_path "$path"; then
    blocked="${blocked:+$blocked, }$path"
  fi
done < <(git diff --name-only -z --diff-filter=ACMR "$computed" HEAD)
if [ -n "$blocked" ]; then
  fail "refusing to push a branch that adds secret-looking paths: $blocked" secret \
    "Remove each path in a new commit through the commit-change skill (git rm --cached <path>), tell the user, then run $RUNNER again." "" "$blocked"
fi

# 5. Push. Never force: a diverged or newer remote branch is refused. Compare
#    with the remote branch of the same name, not @{u}: a branch made from
#    origin/main may track main.
remote_ref="refs/remotes/origin/$branch"
git fetch --quiet origin "+refs/heads/$branch:$remote_ref" 2>/dev/null || true
if git rev-parse --verify --quiet "$remote_ref" >/dev/null; then
  read -r behind ahead < <(git rev-list --left-right --count "$remote_ref...HEAD")
  if [ "$behind" -gt 0 ]; then
    fail "origin/$branch has $behind commit(s) this branch does not." diverged \
      "git merge origin/$branch (never rebase over pushed commits, never force-push), then run $RUNNER again."
  elif [ "$ahead" -gt 0 ]; then
    git push origin "HEAD:refs/heads/$branch" || fail "git push failed." push "Read the git output above, fix the cause, then run $RUNNER again."
  fi
else
  git push --set-upstream origin "HEAD:refs/heads/$branch" || fail "git push failed." push "Read the git output above, fix the cause, then run $RUNNER again."
fi

# 6. Create, or reuse the open pull request for this branch. `gh pr edit`
#    fails on this repository's classic Projects field, so every edit after
#    creation goes through `gh api`.
repo="$(gh repo view --json nameWithOwner --jq .nameWithOwner)" || fail "cannot read the repository name." auth "gh auth status, then run $RUNNER again."
me="$(gh api user --jq .login)" || fail "cannot read the gh login." auth "gh auth status, then run $RUNNER again."

number="$(gh pr list --head "$branch" --base "$base" --state open --json number --jq '.[0].number // empty')"
if [ -n "$number" ]; then
  gh api -X PATCH "repos/$repo/pulls/$number" -f title="$title" -F body=@"$body_file" >/dev/null ||
    fail "could not update pull request #$number." create "Read the gh output above, fix the cause, then run $RUNNER again."
else
  create_args=(--base "$base" --head "$branch" --title "$title" --body-file "$body_file")
  [ "$draft" = true ] && create_args+=(--draft)
  url="$(gh pr create "${create_args[@]}")" || fail "gh pr create failed." create "Read the gh output above, fix the cause, then run $RUNNER again."
  number="${url##*/}"
fi

# Assignee, labels and reviewers, each additive. Labels outside the allowlist
# that a person or bot added are left alone.
gh api -X POST "repos/$repo/issues/$number/assignees" -f "assignees[]=$me" >/dev/null ||
  printf 'pr-runner: warning: could not assign #%s to %s.\n' "$number" "$me" >&2
if [ "${#labels[@]}" -gt 0 ]; then
  label_args=()
  for label in "${labels[@]}"; do label_args+=(-f "labels[]=$label"); done
  gh api -X POST "repos/$repo/issues/$number/labels" "${label_args[@]}" >/dev/null ||
    fail "could not add labels to #$number." label "Check each label exists on the repository, then run $RUNNER again." "$(IFS=,; printf '%s' "${labels[*]}")"
fi
if [ "${#reviewers[@]}" -gt 0 ]; then
  reviewer_args=()
  for reviewer in "${reviewers[@]}"; do reviewer_args+=(-f "reviewers[]=$reviewer"); done
  gh api -X POST "repos/$repo/pulls/$number/requested_reviewers" "${reviewer_args[@]}" >/dev/null ||
    fail "could not request reviewers on #$number." create "Check each login has access, then run $RUNNER again."
fi

gh pr view "$number" --json url --jq .url
